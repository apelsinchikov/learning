const YN = (question, options, correct, explain) => ({ prompt: question, options, correct, explain });

/* Верный ответ не должен всегда стоять первым: сдвигаем варианты по кругу, номер верного пересчитывается. */
function spread(questions) {
    return questions.map((question, index) => {
        const size = question.options.length;
        const shift = (index * 2 + 1) % size;
        const options = question.options.map((_, position) => question.options[(position - shift + size) % size]);

        return { ...question, options, correct: (question.correct + shift) % size };
    });
}

